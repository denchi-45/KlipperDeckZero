#pragma once

#include "transport.h"

#include <nlohmann/json.hpp>

#include <chrono>
#include <cstdint>
#include <deque>
#include <functional>
#include <map>
#include <memory>
#include <mutex>
#include <string>

namespace moonraker {

using Json = nlohmann::json;
using Clock = std::chrono::steady_clock;

struct RpcError {
    int code{0};
    std::string message;
};

// Error codes produced locally (not by Moonraker).
constexpr int kErrorDisconnected = -32000;
constexpr int kErrorTimeout = -32001;
constexpr int kErrorSendFailed = -32002;

struct RpcResponse {
    bool ok{false};
    Json result;
    RpcError error;
    bool local_error{false};  // generated by JsonRpcClient (timeout, send failure, disconnect), not the server
};

// JSON-RPC 2.0 client on top of a Transport.
//
// Transport events are queued (thread safe) and dispatched by poll(), so every
// handler registered here runs on the thread calling poll() — the LVGL thread.
class JsonRpcClient {
public:
    using ResponseHandler = std::function<void(const RpcResponse& response)>;
    using NotificationHandler = std::function<void(const std::string& method, const Json& params)>;
    using ConnectionHandler = std::function<void(bool connected, const std::string& reason)>;

    static constexpr std::chrono::milliseconds kDefaultTimeout{10000};

    explicit JsonRpcClient(std::unique_ptr<Transport> transport);
    ~JsonRpcClient();

    JsonRpcClient(const JsonRpcClient&) = delete;
    JsonRpcClient& operator=(const JsonRpcClient&) = delete;

    void set_notification_handler(NotificationHandler handler);
    void set_connection_handler(ConnectionHandler handler);

    void open();
    void close();
    bool connected() const;
    std::string describe() const;

    // Sends a request. The handler is invoked exactly once from poll(): with the
    // result, the server error, a timeout, or a disconnect. Returns the request id.
    uint64_t call(const std::string& method,
                  Json params,
                  ResponseHandler handler,
                  std::chrono::milliseconds timeout = kDefaultTimeout);
    uint64_t call(const std::string& method, ResponseHandler handler) {
        return call(method, Json(), std::move(handler));
    }

    // Dispatches queued transport events and expires timed-out requests.
    void poll(Clock::time_point now = Clock::now());

    std::size_t pending_requests() const;

    // poll() time of the most recently dispatched frame (or Opened) from the server.
    Clock::time_point last_message_at() const;

private:
    struct PendingRequest {
        std::string method;
        ResponseHandler handler;
        Clock::time_point deadline;
        int failure_code{0};  // set when the request could not be sent at all
    };

    struct QueuedEvent {
        TransportEventType type;
        std::string payload;
    };

    void handle_message(const std::string& text);
    void fail_all_pending(int code, const std::string& message);
    void complete(uint64_t id, const RpcResponse& response);

    std::unique_ptr<Transport> transport_;
    std::mutex queue_mutex_;
    std::deque<QueuedEvent> queue_;

    bool connected_{false};
    uint64_t next_id_{1};
    std::map<uint64_t, PendingRequest> pending_;
    NotificationHandler notification_handler_;
    ConnectionHandler connection_handler_;
    Clock::time_point last_poll_{Clock::now()};
    Clock::time_point last_message_at_{};
};

} // namespace moonraker
